<?php

declare(strict_types=1);

function requiredEnv(string $name): string
{
    $value = getenv($name);
    if ($value === false || $value === '') {
        throw new RuntimeException("Missing required environment variable: {$name}");
    }

    return $value;
}

function writeConfig(array $values): void
{
    $config = "<?php\n\n// Generated by the Docker quickstart. Do not commit this file.\n";
    foreach ($values as $name => $value) {
        $config .= "\$config[" . var_export($name, true) . '] = ' . var_export($value, true) . ";\n";
    }

    $path = '/var/www/html/config.local.php';
    $temporaryPath = $path . '.tmp';
    if (file_put_contents($temporaryPath, $config, LOCK_EX) === false || !rename($temporaryPath, $path)) {
        throw new RuntimeException('Unable to write MyAAC configuration.');
    }
}

$host = requiredEnv('CANARY_DB_HOST');
$port = requiredEnv('CANARY_DB_PORT');
$database = requiredEnv('CANARY_DB_NAME');
$user = requiredEnv('CANARY_DB_USER');
$password = requiredEnv('CANARY_DB_PASSWORD');

$pdo = null;
for ($attempt = 1; $attempt <= 60; $attempt++) {
    try {
        $pdo = new PDO(
            "mysql:host={$host};port={$port};dbname={$database};charset=utf8mb4",
            $user,
            $password,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );

        $accounts = $pdo->query("SHOW TABLES LIKE 'accounts'");
        if ($accounts !== false && $accounts->fetchColumn() !== false) {
            break;
        }
    } catch (PDOException) {
        // The Canary entrypoint may still be importing its schema.
    }

    if ($attempt === 60) {
        throw new RuntimeException('Canary database schema did not become available in time.');
    }

    sleep(2);
}

if (!$pdo instanceof PDO) {
    throw new RuntimeException('Could not connect to the Canary database.');
}

$myaacTables = $pdo->query("SHOW TABLES LIKE 'myaac_config'");
if ($myaacTables === false || $myaacTables->fetchColumn() === false) {
    $schema = file_get_contents('/var/www/html/install/includes/schema.sql');
    if ($schema === false) {
        throw new RuntimeException('Could not read the MyAAC schema.');
    }

    $pdo->exec($schema);
}

$adminAccount = requiredEnv('MYAAC_ADMIN_ACCOUNT');
$adminEmail = requiredEnv('MYAAC_ADMIN_EMAIL');
$adminPassword = requiredEnv('MYAAC_ADMIN_PASSWORD');
$adminPlayer = requiredEnv('MYAAC_ADMIN_PLAYER');

// A new Canary schema includes the insecure default god/god account at id 1.
// Replace it only when it is still the pristine account; existing worlds are
// never modified by this quickstart bootstrap.
$defaultAccount = $pdo->prepare('SELECT `name` FROM `accounts` WHERE `id` = 1');
$defaultAccount->execute();
if ($defaultAccount->fetchColumn() === 'god') {
    $update = $pdo->prepare(
        'UPDATE `accounts` SET `name` = ?, `email` = ?, `password` = SHA1(?), `type` = 6, `creation` = UNIX_TIMESTAMP() WHERE `id` = 1'
    );
    $update->execute([$adminAccount, $adminEmail, $adminPassword]);

    // The test seed can already provide the requested administrator player.
    // Keep it intact instead of colliding with the pristine player at id 7.
    $existingAdminPlayer = $pdo->prepare('SELECT `id` FROM `players` WHERE `name` = ? LIMIT 1');
    $existingAdminPlayer->execute([$adminPlayer]);
    if ($existingAdminPlayer->fetchColumn() === false) {
        $player = $pdo->prepare('SELECT `name` FROM `players` WHERE `id` = 7');
        $player->execute();
        if ($player->fetchColumn() === 'GOD') {
            $renamePlayer = $pdo->prepare('UPDATE `players` SET `name` = ?, `account_id` = 1, `group_id` = 6 WHERE `id` = 7');
            $renamePlayer->execute([$adminPlayer]);
        }
    }
}

writeConfig([
    'installed' => true,
    'env' => 'prod',
    'server_path' => '/canary/',
    'database_host' => $host,
    'database_port' => $port,
    'database_user' => $user,
    'database_password' => $password,
    'database_name' => $database,
    'database_encryption' => 'sha1',
    'site_url' => requiredEnv('MYAAC_SITE_URL'),
    'client' => (int) requiredEnv('MYAAC_CLIENT_VERSION'),
    'timezone' => requiredEnv('MYAAC_TIMEZONE'),
    'mail_enabled' => false,
    'mail_admin' => $adminEmail,
    'mail_address' => $adminEmail,
]);
